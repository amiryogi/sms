#!/usr/bin/env node
/**
 * Copies the report-card stylesheets from the web app into the mobile app, so
 * the PDF a phone makes looks like the web's printed card:
 *
 *   frontend/.../reportcard/nebSheetStyles.js   NEB_SHEET_CSS
 *   frontend/.../reportcard/PerformanceSheet.jsx PERF_STYLES
 *   frontend/.../reportcard/GradeLegend.jsx      the legend's <style>
 *
 * -> mobile/src/features/report-cards/html/sheetCss.generated.ts
 *
 * Run after changing those web files:  node scripts/sync-report-card-css.js
 * tests/reportCards/sync.test.ts fails while the copy is out of date.
 */
const fs = require("node:fs");
const path = require("node:path");

const WEB = path.resolve(__dirname, "../../frontend/src/components/common/reportcard");
const OUT = path.resolve(__dirname, "../src/features/report-cards/html/sheetCss.generated.ts");

const between = (file, startRe, endRe) => {
  const src = fs.readFileSync(path.join(WEB, file), "utf8");
  const start = src.search(startRe);
  if (start < 0) throw new Error(`${file}: start marker not found`);
  const from = src.indexOf("`", start) + 1;
  const to = src.indexOf("`", from);
  if (to < 0) throw new Error(`${file}: end of template not found`);
  return src.slice(from, to);
};

const build = () => {
  const neb = between("nebSheetStyles.js", /const NEB_SHEET_CSS = `/);
  const perf = between("PerformanceSheet.jsx", /const PERF_STYLES = `/);
  const legend = between("GradeLegend.jsx", /<style>\{`/);
  const lit = (s) => JSON.stringify(s);
  return `// GENERATED by scripts/sync-report-card-css.js from the web app's report-card
// stylesheets. Do not edit: change the web files and run the script.
export const NEB_SHEET_CSS = ${lit(neb)};
export const PERF_SHEET_CSS = ${lit(perf)};
export const GRADE_LEGEND_CSS = ${lit(legend)};
`;
};

module.exports = { build, OUT, WEB };

if (require.main === module) {
  fs.writeFileSync(OUT, build());
  console.log(`Wrote ${path.relative(process.cwd(), OUT)}`);
}
